#!/bin/bash
# Не даём внешнему диску парковать головки (и засыпать).
#
# Два разных механизма, и лечатся они по-разному:
#
#   СОН шпинделя — таймер в мосте коробки, страница Power Condition:
#   SZCT=18000 (30 минут), и он помечен изменяемым. Выключается штатно,
#   `sdparm --clear=STANDBY_Z --set=SZCT=0 --save` — см. mybook-nosleep.sh.
#   Это требует root, зато настоящее решение.
#
#   ПАРКОВКА головок — таймер внутри самого диска. Через USB-мост он
#   недостижим: idle3ctl ходит старым ioctl HDIO_DRIVE_CMD и получает
#   «Invalid argument», APM диск не поддерживает вовсе (hdparm -B), страницы
#   IDLE_A/B/C у моста помечены неизменяемыми. Поменять его можно только вынув
#   диск из коробки и подключив по SATA. Поэтому здесь — единственное, что
#   остаётся: не оставлять диск без дела дольше его таймера парковки.
#
# По SMART диска на res-i3: Load_Cycle_Count 1705 при Power_On_Hours 70, то
# есть головки снимаются примерно раз в 2,5 минуты простоя. Интервал ниже взят
# с двукратным запасом.
#
# Читаем 4 КБ и каждый раз с НОВОГО случайного места большого файла:
#   * без O_DIRECT запрос обслужил бы кэш страниц, до диска бы не дошло;
#   * с одного и того же места его обслужил бы кэш внутри самого диска
#     (там десятки мегабайт), и спящий диск не проснулся бы.
# Случайное смещение по многогигабайтному файлу — это гарантированно платтер.
#
#   mybook-keepalive.sh [точка монтирования] [интервал, с]
#
# Без интервала — одно чтение и выход (так удобно проверять руками). С
# интервалом — крутится в цикле, так его и держит systemd-юнит.
set -u

M=${1:-/mnt/mybook}
EVERY=${2:-0}
CACHE=${XDG_CACHE_HOME:-$HOME/.cache}/mybook-keepalive.target
MIN_FILE=$((2 * 1024 * 1024 * 1024))   # по такому файлу смещение гуляет широко

touch_disk() {
    # диск отвалился или ещё не смонтирован — молча уходим: поднимать шум
    # каждую минуту незачем, об отвалившемся диске скажет сам медиаагент
    mountpoint -q "$M" || return 0

    local target size rnd off
    target=$(cat "$CACHE" 2>/dev/null) || target=''
    if [ -z "$target" ] || [ ! -r "$target" ]; then
        # обход каталогов — единственное дорогое место, поэтому путь запоминаем
        # и ищем заново только когда файл пропал (переехал или удалили)
        target=$(find "$M" -xdev -type f -size +2G -print -quit 2>/dev/null)
        [ -n "$target" ] || return 0
        mkdir -p "$(dirname "$CACHE")" && printf '%s' "$target" > "$CACHE"
    fi

    size=$(stat -c %s "$target" 2>/dev/null) || return 0
    [ "$size" -gt "$MIN_FILE" ] || return 0

    # четыре байта (до 4 294 967 295) плюс $RANDOM: восьмибайтное число bash
    # прочитал бы как ЗНАКОВОЕ, смещение уходило в минус и dd падал
    rnd=$(( $(od -An -tu4 -N4 /dev/urandom | tr -d ' ') * 32768 + RANDOM ))
    off=$(( rnd % (size - 4096) ))
    off=$(( off - off % 4096 ))         # O_DIRECT читает только с выравниванием
    dd if="$target" of=/dev/null bs=4k count=1 skip="$off" \
       iflag=direct,skip_bytes status=none 2>/dev/null
}

if [ "$EVERY" -le 0 ]; then
    touch_disk
    exit 0
fi

# цикл, а не таймер systemd: при интервале в минуту таймер плодил бы по 1440
# запусков в сутки и столько же пар строк в журнале
while :; do
    touch_disk
    sleep "$EVERY"
done
